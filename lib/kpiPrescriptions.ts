export const ALL20_PRESCRIPTIONS_BY_PERIOD: Record<Period, Record<string, KpiPrescription>> = {
  today: ALL20_PRESCRIPTIONS_TODAY,
  week: ALL20_PRESCRIPTIONS_WEEK,
  month: ALL20_PRESCRIPTIONS_MONTH,
  quarter: ALL20_PRESCRIPTIONS_QUARTER,
};

// ─────────────────────────────────────────────
// 조회 헬퍼: period → kpiKey → prescription
// today/week/quarter에 명시적 override가 없으면 month로 fallback.
// (구조적 조언이 period-agnostic한 KPI들 — 예: fixedCost, materialCost, waitTime 등 —
//  은 month advice가 모든 period에 정확히 적용됨. 우회 아니고 설계 의도.)
// ─────────────────────────────────────────────

export function getKpiPrescription(kpiKey: string, period: Period): KpiPrescription | undefined {
  return (
    KPI_PRESCRIPTIONS_BY_PERIOD[period][kpiKey] ??
    KPI_PRESCRIPTIONS_BY_PERIOD.month[kpiKey] ??
    ALL20_PRESCRIPTIONS_BY_PERIOD[period][kpiKey] ??
    ALL20_PRESCRIPTIONS_BY_PERIOD.month[kpiKey]
  );
}

export function hasKpiPrescription(kpiKey: string, period: Period): boolean {
  return getKpiPrescription(kpiKey, period) !== undefined;
}
