// KPI 처방전 — period-scoped 근본 스키마
//
// 왜 별도 파일?
// 1) dashboard.tsx가 이미 1,900줄 넘음 — 처방 4× 확장 시 3,500줄까지 감
// 2) 처방은 period × KPI 조합이라 매트릭스 자료구조가 자연스러움
// 3) 카피 편집·검토 사이클을 분리하면 UI 리팩터와 병행 가능
//
// 구조:
//   RX_BY_PERIOD["today" | "week" | "month" | "quarter"][kpiKey]
//   → month이 baseline. 다른 period는 numeric claim만 재작성, solution/effect/action 재활용.
//   → (풀이) 문단은 개념 설명이라 period-agnostic — 원문 유지.
//
// v0.4 정정 원칙: today/week/quarter도 벤치마크 자체는 KPI_BENCHMARKS를
// 그대로 쓰되, "이번 달 X만 원" 같은 절대 금액 언급만 period 스케일로 치환.
// (rate·비율형 KPI는 값이 동일하므로 KPI별 문맥에 따라 최소 수정.)

export type KpiPrescription = {
  analysis: string[];
  solution: string[];
  effect: string[];
  action: string;
  judgeType?: "ABS" | "REL" | "DERIVED";
  isResultMetric?: boolean;
  upstreamKpiKeys?: string[];
};

export type Period = "today" | "week" | "month" | "quarter";

